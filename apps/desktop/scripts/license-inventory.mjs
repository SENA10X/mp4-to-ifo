// License inventory of the npm packages and Rust crates that end up in the Mac app:
//   third-party/inventory.json                                 machine-readable list
//   third-party/licenses/Rust-crates-and-npm-packages.txt      notices shipped in the app (Open Source Licenses)
// npm: production dependencies of @mp4-to-ifo/desktop (bundled into the UI). Rust: the normal (non-build,
// non-proc-macro) dependency graph of the app binary for aarch64-apple-darwin, from Cargo.lock.
// The toolchain executables (FFmpeg, zimg, dvdauthor, Node.js) are in third-party/sources.json instead.
//
//   node scripts/license-inventory.mjs           write both files
//   node scripts/license-inventory.mjs --check   exit 1 if they are out of date (used by the release)

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(desktop, '../..');
const jsonOut = path.join(repo, 'third-party/inventory.json');
const textOut = path.join(repo, 'third-party/licenses/Rust-crates-and-npm-packages.txt');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$/i;

function licenseFiles(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && LICENSE_FILE.test(e.name))
    .map((e) => e.name)
    .sort();
}

function npmPackages() {
  const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '-w', '@mp4-to-ifo/desktop'], { cwd: repo, encoding: 'utf8' }));
  const found = new Map();
  const walk = (deps) => {
    for (const [name, dep] of Object.entries(deps ?? {})) {
      if (!name.startsWith('@mp4-to-ifo/') && !found.has(`${name}@${dep.version}`)) {
        const dir = path.join(repo, 'node_modules', name);
        const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
        if (pkg.version !== dep.version) throw new Error(`${name}: node_modules has ${pkg.version}, tree has ${dep.version}`);
        const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
        found.set(`${name}@${dep.version}`, { name, version: pkg.version, license: pkg.license, source: `https://www.npmjs.com/package/${name}/v/${pkg.version}`, repository: repository ?? null, dir, licenseFiles: licenseFiles(dir) });
      }
      walk(dep.dependencies);
    }
  };
  walk(tree.dependencies?.['@mp4-to-ifo/desktop']?.dependencies);
  return [...found.values()];
}

function cargoPackages() {
  const meta = JSON.parse(
    execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--offline', '--filter-platform', 'aarch64-apple-darwin'], {
      cwd: path.join(desktop, 'src-tauri'),
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  const packages = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const isProcMacro = (p) => p.targets.some((t) => t.kind.includes('proc-macro'));
  const shipped = new Set();
  const visit = (id) => {
    for (const dep of nodes.get(id).deps) {
      const normal = dep.dep_kinds.some((k) => k.kind === null);
      if (!normal || shipped.has(dep.pkg) || isProcMacro(packages.get(dep.pkg))) continue;
      shipped.add(dep.pkg);
      visit(dep.pkg);
    }
  };
  visit(meta.resolve.root);
  return [...shipped].map((id) => {
    const p = packages.get(id);
    const dir = path.dirname(p.manifest_path);
    return { name: p.name, version: p.version, license: p.license ?? p.license_file ?? null, source: `https://crates.io/crates/${p.name}/${p.version}`, repository: p.repository ?? null, authors: p.authors, dir, licenseFiles: licenseFiles(dir) };
  });
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true });
const npm = npmPackages().sort(byName);
const cargo = cargoPackages().sort(byName);
const strip = ({ dir, ...entry }) => entry;
const inventory = {
  note: 'Generated by apps/desktop/scripts/license-inventory.mjs. Packages shipped inside the Mac app (UI bundle and app binary); the toolchain executables are in sources.json.',
  npm: npm.map(strip),
  cargo: cargo.map(strip),
};

// Notices: each package with its license text(s). Identical texts are printed once and referred to after.
const seen = new Map();
let text = `Open source packages inside MP4 to IFO for macOS

The app's user interface includes the npm packages below, and the app binary is built from the Rust crates
below. Each keeps its own license; MP4 to IFO's MIT license does not apply to them. FFmpeg, zimg, dvdauthor
and Node.js are listed separately (THIRD-PARTY.md). All packages are used unmodified; their source is at the
Source address given for each. A package that contains no license file is under the standard text of its
stated license (the same text appears for other packages below).

npm packages: ${npm.length}. Rust crates: ${cargo.length}.
`;
for (const [title, list] of [['npm packages', npm], ['Rust crates', cargo]]) {
  text += `\n${'='.repeat(100)}\n${title}\n${'='.repeat(100)}\n`;
  for (const p of list) {
    text += `\n${'-'.repeat(100)}\n${p.name} ${p.version}\nLicense: ${p.license ?? 'not stated'}\nSource: ${p.source}${p.repository ? `\nRepository: ${p.repository}` : ''}\n`;
    if (!p.licenseFiles.length) text += `(The package contains no license file.${p.authors?.length ? ` Authors: ${p.authors.join(', ')}.` : ''})\n`;
    for (const file of p.licenseFiles) {
      const body = fs.readFileSync(path.join(p.dir, file), 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trimEnd();
      const first = seen.get(body);
      if (first) text += `\n[${file}: same text as ${first}]\n`;
      else {
        seen.set(body, `${p.name} ${p.version} ${file}`);
        text += `\n[${file}]\n${body}\n`;
      }
    }
  }
}
const json = `${JSON.stringify(inventory, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const stale = [[jsonOut, json], [textOut, text]].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
  if (stale.length) {
    console.error(`license inventory out of date: ${stale.map(([f]) => path.relative(repo, f)).join(', ')} (run node apps/desktop/scripts/license-inventory.mjs)`);
    process.exit(1);
  }
  console.log(`license inventory up to date: ${npm.length} npm packages, ${cargo.length} Rust crates`);
} else {
  fs.writeFileSync(jsonOut, json);
  fs.writeFileSync(textOut, text);
  console.log(`license inventory: ${npm.length} npm packages, ${cargo.length} Rust crates`);
}
